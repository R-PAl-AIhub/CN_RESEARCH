"""Generate 04_experiments_log.md from result files (no hand-typed numbers)."""
import sys
import json
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import numpy as np
import pandas as pd
from analysis_lib import ROOT, CONDS, COND_LABEL, DS_LABEL, MAIN, ABL, load_final, cell, mean_std, significance_table

df = load_final()
sig = significance_table(df)
L = ["# 04 - Experiments log (auto-generated by code/plots/make_experiments_log.py)", ""]

L += ["## 1. Setting", "",
      "- Environment: Windows 11 (build 10.0.26200), AMD Ryzen 7 7435HS (8C/16T), 23.7 GB RAM, Python 3.11.9, TensorFlow 2.21.0 (CPU only, CUDA_VISIBLE_DEVICES=-1), scikit-learn 1.9.1.",
      f"- Runs: {len(df)} final runs = {df.seed.nunique()} seeds x {df.groupby('dataset').cond.nunique().sum()} dataset/condition cells x {df.method.nunique()} methods; test split evaluated once per run.",
      "- Data (real, public): CIC-IoT2023 (46 features; benign vs 12 DDoS types) and N-BaIoT (115 features; benign vs 8 flood attack files, one client per device). Exact duplicates removed before splitting. No synthetic data.",
      "- Protocol: 60/20/20 stratified split per seeded corpus; tuning = random search, 6 trials, identical stream for every method, objective = mean validation F1 over corpora of seeds 0-2 (`results/tuning/*.json`).",
      "- Federated budget shared by all linear methods: T=20 rounds, E=2 local epochs, batch 64, lr/(1+t); MLP: E=1, batch 128.",
      "- Artifacts: `results/raw/final_*.jsonl` (one JSON per run), `results/raw/sens_*.jsonl`, `results/cost_profile.json`, `results/diag_selection_failure.json`, `results/logs/`, `results/archive_v1/` (first pass, superseded, see decisions_log D8).", ""]

L += ["## 2. Test F1 (mean +- std over seeds)", ""]
cols = [(ds, c) for ds, cs in CONDS.items() for c in cs]
hdr = "| method | " + " | ".join(f"{DS_LABEL[ds]} {COND_LABEL[c]}" for ds, c in cols) + " |"
L += [hdr, "|---" * (len(cols) + 1) + "|"]
for m in MAIN + ["abl_localscale", "abl_nosel", "abl_oneshot", "abl_pearson", "abl_lda"]:
    row = [f"{mean_std(cell(df, ds, c, m))[0]:.4f} +- {mean_std(cell(df, ds, c, m))[1]:.4f}" for ds, c in cols]
    L.append(f"| {m} | " + " | ".join(row) + " |")
L += ["", "## 3. Runs with test F1 < 0.9 (descriptive failure count, out of 10 seeds)", ""]
fail = df[df.f1 < 0.9].groupby(["dataset", "cond", "method"]).size().reset_index(name="n_fail")
L += ["| dataset | cond | method | n_fail |", "|---|---|---|---|"] + [f"| {r.dataset} | {r.cond} | {r.method} | {r.n_fail} |" for r in fail.itertuples()]

L += ["", "## 4. Federated vs pooled selection (RQ1 fidelity)", ""]
fs = df[df.method == "fedstat"]
L.append(f"- FedStat-FS subset equals the pooled train-only subset in {(fs.jaccard_vs_pooled == 1).sum()} of {len(fs)} runs (min Jaccard {fs.jaccard_vs_pooled.min():.3f}).")

L += ["", "## 5. Paired tests (A - B, test F1; Wilcoxon raw / Holm over all tests)", "",
      "| dataset | cond | A | B | diff | 95% CI | p raw | p Holm |", "|---|---|---|---|---|---|---|---|"]
for r in sig.itertuples():
    L.append(f"| {r.dataset} | {r.cond} | {r.A} | {r.B} | {r.diff:+.4f} | [{r.ci_lo:+.4f}, {r.ci_hi:+.4f}] | {r.p_w:.3f} | {r.p_w_holm:.3f} |")

L += ["", "## 6. Tuning summary (best mean validation F1 per method)", ""]
rows = []
for ds, cs in CONDS.items():
    for c in cs:
        t = json.load(open(ROOT / "results" / "tuning" / f"{ds}_{c}.json"))
        for m, v in t.items():
            rows.append(f"| {ds} | {c} | {m} | {v['best_val_f1']:.4f} | {min(x['val_f1_min'] for x in v['trials'] if x['hp'] == v['best_hp']):.4f} |")
L += ["| dataset | cond | method | best mean val F1 | min over tuning seeds |", "|---|---|---|---|---|"] + rows

L += ["", "## 7. Issues met and how they were resolved", "",
      "See `decisions_log.md` (D3-D8). In short: 39-feature mirror discarded; N-BaIoT attack files were nested rars; first tuning on a single seed produced diverging step sizes and was replaced by 3-seed tuning;",
      "the Pearson-LDA intersection subset is linearly insufficient on some N-BaIoT seeds (verified with exact solvers, `results/diag_selection_failure.json`) and is reported as a finding.", ""]
(ROOT / "04_experiments_log.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote 04_experiments_log.md", len(L), "lines")
