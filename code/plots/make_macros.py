"""
paper/numbers.tex: every number quoted in the running text is defined here from result files
(usage in main.tex:  \\rv{method}{dataset}{cond}{field},  \\sg{A}{B}{dataset}{cond}{field},  \\nv{name}).
Nothing is typed by hand; the integrity pass greps main.tex for digits that are not macro calls.
"""
import sys
import json
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import numpy as np
from analysis_lib import ROOT, CONDS, load_final, load_sens, cell, mean_std, significance_table, PAIRS
sys.path.insert(0, str(ROOT / "code"))
from fedstat.prep import bytes_uploaded

OUT = ROOT / "paper" / "numbers.tex"
lines = [
    "% AUTO-GENERATED by code/plots/make_macros.py - do not edit",
    "\\newcommand{\\rv}[4]{\\csname res:#1:#2:#3:#4\\endcsname}",
    "\\newcommand{\\sg}[5]{\\csname sig:#1:#2:#3:#4:#5\\endcsname}",
    "\\newcommand{\\nv}[1]{\\csname num:#1\\endcsname}",
]


def d(name, val):
    lines.append(f"\\expandafter\\def\\csname {name}\\endcsname{{{val}}}")


df = load_final()
sens = load_sens()
n_seeds = int(df.seed.nunique())
d("num:seeds", n_seeds)
d("num:runs", len(df))

# ---- per (method, dataset, cond) statistics
for (m, ds, c), g in df.groupby(["method", "dataset", "cond"]):
    for k in ("f1", "rec", "prec", "acc", "fpr", "mcc"):
        mu, sd = mean_std(g[k].to_numpy(float))
        d(f"res:{m}:{ds}:{c}:{k}m", f"{mu:.4f}")
        d(f"res:{m}:{ds}:{c}:{k}s", f"{sd:.4f}")
        d(f"res:{m}:{ds}:{c}:{k}pct", f"{mu * 100:.2f}")
    d(f"res:{m}:{ds}:{c}:nfeat", f"{g.n_feat.mean():.1f}")
    d(f"res:{m}:{ds}:{c}:nfail", int((g.f1 < 0.9).sum()))
    d(f"res:{m}:{ds}:{c}:nruns", len(g))
    d(f"res:{m}:{ds}:{c}:f1min", f"{g.f1.min():.4f}")
    d(f"res:{m}:{ds}:{c}:f1med", f"{g.f1.median():.4f}")

# ---- overall failure counts per method/dataset (F1 < 0.9)
for (m, ds), g in df.groupby(["method", "dataset"]):
    d(f"num:nfail:{m}:{ds}", int((g.f1 < 0.9).sum()))
    d(f"num:nrun:{m}:{ds}", len(g))

# ---- exactness of federated selection (RQ1)
fs = df[df.method == "fedstat"]
d("num:exact_ok", int((fs.jaccard_vs_pooled == 1.0).sum()))
d("num:exact_total", len(fs))
d("num:exact_minjac", f"{fs.jaccard_vs_pooled.min():.3f}")
# same subset as the pooled train-only method (senior_noleak) - independent check from the 'keep' lists
ok = tot = 0
for (ds, c, s), g in df.groupby(["dataset", "cond", "seed"]):
    a = g[g.method == "fedstat"]
    b = g[g.method == "senior_noleak"]
    if len(a) and len(b):
        tot += 1
        ok += int(sorted(a.iloc[0]["keep"]) == sorted(b.iloc[0]["keep"]))
d("num:same_as_pooled_ok", ok)
d("num:same_as_pooled_total", tot)

# ---- local vote vs federated agreement
for ds, cs in CONDS.items():
    for c in cs:
        a = df[(df.dataset == ds) & (df.cond == c) & (df.method == "fedstat")].sort_values("seed")
        b = df[(df.dataset == ds) & (df.cond == c) & (df.method == "local_prep_fedavg")].sort_values("seed")
        jac = [len(set(x) & set(y)) / max(len(set(x) | set(y)), 1) for x, y in zip(a["keep"], b["keep"])]
        d(f"num:jaclocal:{ds}:{c}", f"{np.mean(jac):.2f}")
        d(f"num:nfeatlocal:{ds}:{c}", f"{b.n_feat.mean():.1f}")

# ---- significance
sig = significance_table(df)
for _, r in sig.iterrows():
    base = f"sig:{r.A}:{r.B}:{r.dataset}:{r.cond}"
    d(f"{base}:diff", f"{r['diff']:+.4f}")
    d(f"{base}:cilo", f"{r['ci_lo']:+.4f}")
    d(f"{base}:cihi", f"{r['ci_hi']:+.4f}")
    d(f"{base}:pw", "$<$0.001" if r.p_w < 1e-3 else f"{r.p_w:.3f}")
    d(f"{base}:pwholm", "$<$0.001" if r.p_w_holm < 1e-3 else f"{r.p_w_holm:.3f}")
    d(f"{base}:pwholmpair", "$<$0.001" if r.p_w_holm_pair < 1e-3 else f"{r.p_w_holm_pair:.3f}")
d("num:ntests", len(sig))
d("num:minp", f"{2 / 2 ** n_seeds:.4f}")

# ---- communication / statistics sizes
for dd, name in ((46, "cic"), (115, "nba")):
    d(f"num:statbytes:{name}", f"{bytes_uploaded(dd) / 1024:.1f}")
mo = df[(df.method == "fedstat")]
d("num:modelKB:cic", f"{mo[mo.dataset == 'ciciot'].comm_model_bytes.mean() / 1024:.1f}")

# ---- dataset / dedup facts
for name in ("ciciot", "nbaiot"):
    rep = json.load(open(ROOT / "data" / "processed" / f"{name}_dedup_report.json"))
    d(f"num:dedup_removed:{name}", f"{rep['duplicates_removed']:,}")
    d(f"num:dedup_frac:{name}", f"{100 * rep['duplicates_removed'] / rep['rows_before']:.1f}")
    d(f"num:pool:{name}", f"{rep['rows_before']:,}")

# ---- Phase-1 reproduction of the senior code and TF port
ref = json.load(open(ROOT / "code" / "senior_repro" / "outputs" / "results" / "experiment_results.json"))
for tag, blk in (("cent", ref["centralized_svm"]), ("fed5", ref["federated_svm"]["5"]), ("rf", ref["comparative_models"]["Random Forest"]),
                 ("ann", ref["comparative_models"]["ANN"]), ("if", ref["comparative_models"]["Isolation Forest"])):
    d(f"num:senior_f1:{tag}", f"{blk['f1_score']:.4f}")
d("num:senior_fpr:fed5", f"{ref['federated_svm']['5']['fpr'] * 100:.2f}")
d("num:senior_fnr:fed5", f"{ref['federated_svm']['5']['fnr'] * 100:.2f}")
tp = json.load(open(ROOT / "results" / "phase1_tf_port_check.json"))
for k in ("tf_svm_central_hinge", "tf_svm_central_sqhinge", "tf_fed5_oneshot_avg_sqhinge", "tf_fed5_fedavg_warm_sqhinge", "keras_mlp_central"):
    d(f"num:tf:{k}", f"{tp[k]['f1']:.4f}")

# ---- cost profile
if (ROOT / "results" / "cost_profile.json").exists():
    cp = json.load(open(ROOT / "results" / "cost_profile.json"))
    for m, r in cp.items():
        d(f"num:cost:{m}:train", f"{r['train_sec']:.1f}")
        d(f"num:cost:{m}:infer", f"{r['infer_ms_per_1k']:.2f}")
        d(f"num:cost:{m}:params", f"{r['n_params']:,}")
        d(f"num:cost:{m}:mem", f"{r['peak_incremental_mb']:.0f}")
        d(f"num:cost:{m}:prep", f"{r['prep_sec']:.2f}")

# ---- sensitivity summary (validation, dir0.3)
if len(sens):
    for (m, p), g in sens.groupby(["method", "param"]):
        agg = g.groupby("value").f1.mean()
        d(f"num:sens:{m}:{p}:min", f"{agg.min():.4f}")
        d(f"num:sens:{m}:{p}:max", f"{agg.max():.4f}")
        d(f"num:sens:{m}:{p}:argmax", f"{agg.idxmax()}")

# ---- feature counts and the FedStat-FS vs federated-MLP gap (CIC-IoT2023), used in the prose
for m, tag in (("abl_nosel", "nosel"), ("fedstat", "fedstat"), ("abl_pearson", "pearson")):
    for ds in ("ciciot", "nbaiot"):
        d(f"num:nfeat:{tag}:{ds}", f"{df[(df.method == m) & (df.dataset == ds)].n_feat.mean():.0f}")
gaps = [(cell(df, "ciciot", c, "fedstat_mlp") - cell(df, "ciciot", c, "fedstat")).mean() * 100 for c in CONDS["ciciot"]]
d("num:mlpgap:min", f"{min(gaps):.2f}")
d("num:mlpgap:max", f"{max(gaps):.2f}")

# ---- selection-failure diagnostic (exact solvers on the pooled TRAIN split; code/diagnostics_selection_failure.py)
dg = ROOT / "results" / "diag_selection_failure.json"
if dg.exists():
    for k, r in json.load(open(dg)).items():
        d(f"num:diag:{r['seed']}:{r['mode']}:nfeat", r["n_feat"])
        d(f"num:diag:{r['seed']}:{r['mode']}:trainf1", f"{r['svm_train_f1']:.3f}")
        d(f"num:diag:{r['seed']}:{r['mode']}:testf1", f"{r['svm_test_f1']:.3f}")
        d(f"num:diag:{r['seed']}:{r['mode']}:lrf1", f"{r['logreg_test_f1']:.3f}")

OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", OUT, len(lines), "lines")
