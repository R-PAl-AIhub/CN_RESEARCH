"""
Generate 05_visuals_index.md from the LaTeX sources (one row per FLOAT, in order of appearance = paper numbering).
Phase-6 integrity checks: every registered file exists, every float has a caption, every float is \\ref'ed in the text,
every equation label is referenced.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PAPER = ROOT / "paper"


def expand(t):
    return re.sub(r"\\input\{([^}]+)\}", lambda m: expand((PAPER / (m.group(1) if m.group(1).endswith(".tex") else m.group(1) + ".tex")).read_text(encoding="utf-8")), t)


main = (PAPER / "main.tex").read_text(encoding="utf-8")
text = expand(main[main.index("\\begin{abstract}"):])
text = re.sub(r"(?m)^\s*%.*$", "", text)

REG = {  # any label of the float -> (files, script)
    "fig:arch": (["figures/diagrams/d1_system_architecture"], "code/plots/diagrams.py::d1_architecture"),
    "fig:pipeline": (["figures/diagrams/d2_pipeline_flowchart"], "code/plots/diagrams.py::d2_pipeline"),
    "fig:flows": (["figures/diagrams/d3_preprocessing_flowchart", "figures/diagrams/d6_algorithm_flowchart"], "code/plots/diagrams.py::d3_preprocessing, d6_algorithm"),
    "fig:models": (["figures/diagrams/d4_model_architecture"], "code/plots/diagrams.py::d4_models"),
    "fig:cmp": (["figures/diagrams/d5_senior_vs_proposed"], "code/plots/diagrams.py::d5_comparison"),
    "fig:bar": (["figures/results/fig_bar_f1"], "code/plots/make_figures.py::fig_bar_f1"),
    "fig:abl": (["figures/results/fig_ablation", "figures/results/fig_selection"], "code/plots/make_figures.py::fig_ablation, fig_selection"),
    "fig:curves": (["figures/results/fig_curves", "figures/results/fig_confusion"], "code/plots/make_figures.py::fig_curves, fig_confusion"),
    "fig:sens": (["figures/results/fig_sensitivity", "figures/results/fig_error"], "code/plots/make_figures.py::fig_sensitivity, fig_error"),
    "tab:related": (["results/tables/table8_related.csv", "results/tables/table6_literature.csv"], "code/plots/make_tables.py (related-work features + quoted results; literature numbers come from the cited sources)"),
    "tab:datasets": (["results/tables/table1_datasets.csv"], "code/plots/make_tables.py (datasets)"),
    "tab:setup": (["results/tables/table2_setup.csv", "results/tables/tuned_hyperparameters.csv"], "code/plots/make_tables.py (setup, search spaces)"),
    "tab:main": (["results/tables/table3_main_f1.csv", "results/tables/table3_main_all_metrics.csv"], "code/plots/make_tables.py (main results)"),
    "tab:ablation": (["results/tables/table4_ablation.csv", "results/tables/table4_ablation_numeric.csv"], "code/plots/make_tables.py (ablation)"),
    "tab:cost": (["results/tables/table7_cost.csv", "results/cost_profile.json"], "code/run_cost.py + code/plots/make_tables.py (cost)"),
    "tab:sig": (["results/tables/table5_significance.csv", "results/tables/table5_significance_all.csv"], "code/plots/make_tables.py (significance)"),
    "tab:base": (["results/tables/base_scoreboard.csv", "results/tables/base_tests.csv"], "code/plots/base_compare.py (base-paper comparison, re-implemented)"),
}
IMPL = {"eq:obj": "fl.py::fedavg_svm", "eq:A": "prep.py::client_round_a", "eq:A2": "prep.py::fit_federated", "eq:B": "prep.py::client_round_b",
        "eq:var": "prep.py::select_from_moments", "eq:pear": "prep.py::select_from_moments", "eq:sw": "prep.py::fit_federated",
        "eq:lda": "prep.py::select_from_moments (pinv)", "eq:sel": "prep.py::select_from_moments, fit_federated", "eq:loss": "models.py::_make_epoch_fn",
        "eq:avg": "fl.py::_wavg, fedavg_svm", "eq:metrics": "metrics.py::scores"}


def braced(s, i):
    depth = 0
    for j in range(i, len(s)):
        if s[j] == "{":
            depth += 1
        elif s[j] == "}":
            depth -= 1
            if depth == 0:
                return s[i + 1:j]
    return ""


def roman(n):
    r = ""
    for v, s in ((10, "X"), (9, "IX"), (5, "V"), (4, "IV"), (1, "I")):
        while n >= v:
            r += s
            n -= v
    return r


floats = []
for m in re.finditer(r"\\begin\{(figure|table)\*?\}(.*?)\\end\{\1\*?\}", text, re.S):
    blk = m.group(2)
    i = blk.find("\\caption{")
    cap = re.sub(r"\s+", " ", braced(blk, i + len("\\caption"))) if i >= 0 else None
    labels = re.findall(r"\\label\{([^}]+)\}", blk)
    floats.append((m.group(1), cap, labels))

problems, out = [], ["# 05 - Visuals index (auto-generated by code/plots/make_visuals_index.py)", "",
                     "One row per float, in paper order (= paper numbering). Integrity checks: files exist, caption present, referenced in the text.", ""]
for kind, title in (("figure", "Figures"), ("table", "Tables")):
    out += [f"## {title}", "", "| No. | Labels | Caption | Files | Script | Referenced |", "|---|---|---|---|---|---|"]
    n = 0
    for k, cap, labels in floats:
        if k != kind:
            continue
        n += 1
        reg = next((REG[l] for l in labels if l in REG), None)
        if reg is None:
            problems.append(f"{labels}: not registered")
            reg = ([], "UNREGISTERED")
        files, script = reg
        ok_files = bool(files) and all(any((ROOT / f).parent.glob((ROOT / f).name + "*")) for f in files)
        if not ok_files:
            problems.append(f"{labels}: files missing {files}")
        if cap is None:
            problems.append(f"{labels}: no caption")
        refd = any(re.search(r"\\ref\{" + re.escape(l) + r"\}", text) for l in labels)
        if not refd:
            problems.append(f"{labels}: never referenced")
        num = roman(n) if kind == "table" else str(n)
        out.append(f"| {'Table' if kind == 'table' else 'Fig.'} {num} | {', '.join('`'+l+'`' for l in labels)} | {cap} | {'; '.join('`'+f+'`' for f in files)} | `{script}` | {'yes' if refd else '**NO**'} |")
    out.append("")

eqs = re.findall(r"\\label\{(eq:[^}]+)\}", text)
out += ["## Equations", "", "| No. | Label | Referenced | Implemented in |", "|---|---|---|---|"]
for i, e in enumerate(eqs, 1):
    refd = bool(re.search(r"\\eqref\{" + re.escape(e) + r"\}", text) or re.search(r"\\ref\{" + re.escape(e) + r"\}", text))
    if not refd:
        problems.append(f"{e}: equation never referenced")
    out.append(f"| ({i}) | `{e}` | {'yes' if refd else '**NO**'} | `{IMPL.get(e, '-')}` |")
out += ["", "## Algorithm", "", "Algorithm 1 (label `alg:main`) in `paper/sec_method.tex`; flowchart Fig. 2 (right); pseudocode with complexity, mirrors `code/fedstat/prep.py::fit_federated` and `code/fedstat/fl.py::fedavg_svm`.", ""]
out += ["## Integrity check result", ""]
out += ["All checks passed."] if not problems else [f"- PROBLEM: {p}" for p in problems]
(ROOT / "05_visuals_index.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("\n".join(out[-4:]))
